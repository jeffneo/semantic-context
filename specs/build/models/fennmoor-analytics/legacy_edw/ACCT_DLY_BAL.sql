SELECT
  a.ACCT_NO AS ACCT_NBR,
  b.BAL_DT,
  b.LEDGER_BAL_AMT AS LDGR_BAL_AMT,
  b.AVAIL_BAL_AMT AS AVL_BAL_AMT,
  a.PROD_CD,
  a.BRNCH_ID AS BRNCH_NBR,
  CURRENT_TIMESTAMP() AS LOAD_TS
FROM `fennmoor-raw.core_banking_cdc.ACCOUNT_BALANCE_DLY` b
JOIN `fennmoor-raw.core_banking_cdc.ACCOUNT` a ON a.ACCT_ID = b.ACCT_ID
